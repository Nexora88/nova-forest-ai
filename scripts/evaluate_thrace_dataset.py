#!/usr/bin/env python3
"""Chronological baseline/model evaluation for the Thrace pilot CSV.

This script evaluates a proxy label (FIRMS detection near a fixed site), not
confirmed forest-fire occurrence or calibrated fire probability.
"""
from __future__ import annotations

import argparse
import csv
import json
import math
from datetime import date
from pathlib import Path

FEATURES = [
    "temperature_2m_max", "temperature_2m_min",
    "relative_humidity_2m_min", "relative_humidity_2m_max",
    "wind_speed_10m_max", "precipitation_sum",
]


def wilson_interval(successes: int, total: int, z: float = 1.96):
    if total <= 0:
        return None
    p = successes / total
    denominator = 1 + z * z / total
    centre = (p + z * z / (2 * total)) / denominator
    margin = z * math.sqrt((p * (1 - p) + z * z / (4 * total)) / total) / denominator
    return [round(max(0.0, centre - margin), 4), round(min(1.0, centre + margin), 4)]


def confusion(y_true, y_pred):
    tp = sum(a == 1 and b == 1 for a, b in zip(y_true, y_pred))
    tn = sum(a == 0 and b == 0 for a, b in zip(y_true, y_pred))
    fp = sum(a == 0 and b == 1 for a, b in zip(y_true, y_pred))
    fn = sum(a == 1 and b == 0 for a, b in zip(y_true, y_pred))
    precision = tp / (tp + fp) if tp + fp else None
    recall = tp / (tp + fn) if tp + fn else None
    specificity = tn / (tn + fp) if tn + fp else None
    accuracy = (tp + tn) / len(y_true) if y_true else None
    balanced = ((recall + specificity) / 2) if recall is not None and specificity is not None else None
    return {
        "n": len(y_true), "positive_support": sum(y_true), "negative_support": len(y_true) - sum(y_true),
        "confusion_matrix": {"tn": tn, "fp": fp, "fn": fn, "tp": tp},
        "precision": precision, "recall_sensitivity": recall, "specificity": specificity,
        "accuracy": accuracy, "balanced_accuracy": balanced,
        "accuracy_wilson_95_ci": wilson_interval(tp + tn, len(y_true)),
        "recall_wilson_95_ci": wilson_interval(tp, tp + fn),
        "precision_wilson_95_ci": wilson_interval(tp, tp + fp),
        "warning": "Confidence intervals describe binomial sampling uncertainty only; they do not correct label error, temporal dependence, site-selection bias, or provider omissions.",
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", required=True, help="Dataset CSV generated by build_thrace_fire_dataset.py")
    parser.add_argument("--test-start", required=True, help="Chronological test period starts on this ISO date")
    parser.add_argument("--output", default="data/research/thrace_evaluation_report.json")
    parser.add_argument("--minimum-training-class", type=int, default=20)
    args = parser.parse_args(argv)
    cutoff = date.fromisoformat(args.test_start)
    rows = []
    with Path(args.input).open(encoding="utf-8-sig", newline="") as stream:
        for row in csv.DictReader(stream):
            try:
                day = date.fromisoformat(row["date"])
                label = int(row["firms_detection_within_radius"])
                features = [float(row[key]) for key in FEATURES]
                if label not in (0, 1) or not all(math.isfinite(x) for x in features):
                    continue
                rows.append({"date": day, "label": label, "features": features, "site_id": row.get("site_id", "")})
            except (KeyError, TypeError, ValueError):
                continue
    train = [row for row in rows if row["date"] < cutoff]
    test = [row for row in rows if row["date"] >= cutoff]
    y_train = [row["label"] for row in train]
    y_test = [row["label"] for row in test]
    report = {
        "created_at_utc": __import__("datetime").datetime.now(__import__("datetime").timezone.utc).isoformat(),
        "input": str(Path(args.input)),
        "label_definition": "FIRMS thermal anomaly within radius; proxy label only, not confirmed fire ground truth",
        "features": FEATURES,
        "test_start": cutoff.isoformat(),
        "split_method": "chronological, no random split",
        "rows_after_complete_case_filter": len(rows),
        "train": {"n": len(train), "positive": sum(y_train), "negative": len(y_train) - sum(y_train)},
        "test": {"n": len(test), "positive": sum(y_test), "negative": len(y_test) - sum(y_test)},
        "metrics": {},
        "limitations": [
            "This evaluation cannot establish confirmed-fire prediction performance because labels are FIRMS detection proxies.",
            "Fixed pilot anchors may not represent forests or all of Thrace.",
            "Adjacent daily rows are temporally dependent; Wilson intervals do not account for this.",
            "Results must not be described as calibrated probabilities or operational warnings.",
        ],
    }
    if not train or not test:
        report["status"] = "not_evaluable"
        report["reason"] = "Both a non-empty pre-cutoff training period and post-cutoff test period are required."
    elif len(set(y_test)) < 2:
        report["status"] = "not_evaluable"
        report["reason"] = "The held-out period contains only one label class; balanced comparison is not estimable."
    else:
        # Majority baseline is an essential reference even when ML is not supportable.
        majority = 1 if sum(y_train) > len(y_train) / 2 else 0
        report["metrics"]["majority_class_baseline"] = confusion(y_test, [majority] * len(y_test))
        # Prespecified transparent heuristic baseline; it is an indicator, not a calibrated probability.
        rule_predictions = []
        for row in test:
            tmax, _tmin, rh_min, _rh_max, wind_max, precip = row["features"]
            rule_predictions.append(int(tmax >= 30 and rh_min <= 35 and wind_max >= 20 and precip <= 1))
        report["metrics"]["fixed_weather_rule_baseline"] = confusion(y_test, rule_predictions)
        class_counts = {value: y_train.count(value) for value in (0, 1)}
        if min(class_counts.values()) < args.minimum_training_class:
            report["metrics"]["logistic_regression"] = {
                "status": "not_run",
                "reason": f"Training needs at least {args.minimum_training_class} rows of each class; found {class_counts}.",
            }
        else:
            try:
                from sklearn.pipeline import make_pipeline
                from sklearn.preprocessing import StandardScaler
                from sklearn.linear_model import LogisticRegression
                model = make_pipeline(StandardScaler(), LogisticRegression(class_weight="balanced", max_iter=1000, random_state=42))
                model.fit([r["features"] for r in train], y_train)
                predictions = [int(x) for x in model.predict([r["features"] for r in test])]
                probabilities = [float(x) for x in model.predict_proba([r["features"] for r in test])[:, 1]]
                report["metrics"]["logistic_regression"] = {
                    "status": "evaluated",
                    **confusion(y_test, predictions),
                    "probability_note": "Raw model scores are not calibrated fire probabilities.",
                    "mean_predicted_score": round(sum(probabilities) / len(probabilities), 4),
                }
            except ImportError:
                report["metrics"]["logistic_regression"] = {"status": "not_run", "reason": "scikit-learn is not installed."}
        report["status"] = "evaluated_proxy_labels"
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps({"status": report["status"], "train": report["train"], "test": report["test"], "output": str(output)}, ensure_ascii=False, indent=2))
    return 0 if report["status"] != "not_evaluable" else 2


if __name__ == "__main__":
    raise SystemExit(main())
